#!/usr/bin/env bash
#
# Validate messages against the Conventional Commits specification
# (https://www.conventionalcommits.org/en/v1.0.0/). Used by the commit-msg hook
# and by CI when it verifies push/PR commits.
#
# Header grammar:
#   <type>[(<scope>)][!]: <description>
#   * type        one of feat, fix, docs, style, refactor, perf, test, build,
#                 ci, chore, revert
#   * scope       optional, lowercase: letters, digits, '.', '_', '/' or '-'
#   * !           optional, marks a breaking change (BREAKING CHANGE: footer or '!')
#   * description required, no trailing period
#   * header      at most 100 characters
#
# Usage:
#   scripts/validate-conventional-commits.sh --message-file <path>
#       Validate one message file, as passed to the commit-msg hook.
#   scripts/validate-conventional-commits.sh --range <git-range>
#       Validate every non-merge commit in a revision range,
#       e.g. --range origin/main..HEAD
#   scripts/validate-conventional-commits.sh --stdin
#       Validate a message read from standard input.
#   scripts/validate-conventional-commits.sh --text "<message>"
#       Validate a message passed on the command line (handy for PR titles).
#
# Git-generated merge commits ("Merge ...") and revert commits ("Revert \"...\"")
# are skipped. Autosquash subjects ("fixup! ...", "squash! ...", "amend! ...")
# are validated on the message they wrap.
#
set -euo pipefail

types='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'
max_header_length=100
# Kept in a variable: an inline `=~` regex with parentheses confuses bash's parser.
header_pattern='^([^:!(]+)(\(([^\)]*)\))?(!)?: (.*)$'

usage() {
    sed -n '3,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

# Reports one failed validation with its reasons.
report_failure() {
    local label="$1"
    shift
    echo "✗ $label" >&2
    local reason
    for reason in "$@"; do
        echo "  - $reason" >&2
    done
}

# Validates one message; prints every problem found and returns 1 if any.
validate_message() {
    local label="$1"
    local message="$2"
    local -a lines=()
    local line

    while IFS= read -r line; do
        # `git commit --verbose` appends the staged diff after a scissors line.
        if [[ "$line" == *"------------------------ >8 ------------------------"* ]]; then
            break
        fi
        lines+=("$line")
    done <<<"$message"

    local header='' header_index=-1
    local i
    for i in "${!lines[@]}"; do
        line="${lines[$i]}"
        [[ -z "${line//[[:space:]]/}" ]] && continue
        [[ "$line" == \#* ]] && continue
        header="$line"
        header_index=$i
        break
    done

    if [[ -z "$header" ]]; then
        report_failure "$label" "the message is empty"
        return 1
    fi

    local subject="$header"
    if [[ "$subject" =~ ^(fixup|squash|amend)!\ (.+)$ ]]; then
        subject="${BASH_REMATCH[2]}"
    fi

    # Messages generated by git itself do not follow the convention.
    if [[ "$subject" =~ ^Merge\  || "$subject" =~ ^Revert\ \" ]]; then
        return 0
    fi

    local -a problems=()
    local type='' scope_written='' scope='' description=''

    if (( ${#subject} > max_header_length )); then
        problems+=("the header is ${#subject} characters long; the limit is ${max_header_length}")
    fi
    if [[ "$subject" == *. ]]; then
        problems+=("the header ends with a period; drop it")
    fi

    if [[ "$subject" =~ $header_pattern ]]; then
        type="${BASH_REMATCH[1]}"
        scope_written="${BASH_REMATCH[2]}"
        scope="${BASH_REMATCH[3]}"
        description="${BASH_REMATCH[5]}"

        if [[ "|$types|" != *"|$type|"* ]]; then
            problems+=("unknown type '$type' (allowed: ${types//|/, })")
        fi
        if [[ -n "$scope_written" ]]; then
            if [[ -z "$scope" ]]; then
                problems+=("the scope is empty: write '$type(scope): ...' or drop the parentheses")
            elif [[ ! "$scope" =~ ^[a-z0-9][a-z0-9._/-]*$ ]]; then
                problems+=("the scope '$scope' must be lowercase letters, digits, '.', '_', '/' or '-'")
            fi
        fi
        if [[ -z "$description" ]]; then
            problems+=("the description after the colon is empty")
        elif [[ "$description" == " "* ]]; then
            problems+=("write exactly one space after the colon")
        fi
    elif [[ "$subject" != *":"* ]]; then
        problems+=("the header has no '<type>: <description>' form: there is no colon")
    elif [[ "$subject" != *": "* ]]; then
        problems+=("expected '<type>[(<scope>)][!]: <description>' — put one space after the colon")
    else
        problems+=("the header must read '<type>[(<scope>)][!]: <description>'")
    fi

    # A body, when present, must be separated from the header by a blank line.
    local next_index=$((header_index + 1))
    while (( next_index < ${#lines[@]} )); do
        line="${lines[$next_index]}"
        [[ "$line" == \#* ]] && { next_index=$((next_index + 1)); continue; }
        if [[ -n "${line//[[:space:]]/}" ]]; then
            problems+=("the body must start with a blank line after the header")
        fi
        break
    done

    if (( ${#problems[@]} > 0 )); then
        report_failure "$label" "${problems[@]}"
        return 1
    fi

    return 0
}

print_example() {
    cat >&2 <<'EOF'

A message must read like:
  feat(routes): add wildcard path segment matching
  fix!: drop support for the legacy matcher API
  docs: document the recording and verification helpers
  chore(deps): bump Alamofire to 5.12.2

See CONTRIBUTING.md for the type/scope vocabulary enforced by this repository.
EOF
}

mode="${1:-}"
case "$mode" in
    --message-file)
        file="${2:-}"
        if [[ -z "$file" || ! -f "$file" ]]; then
            echo "error: --message-file needs a readable path" >&2
            exit 64
        fi
        if validate_message "$(basename "$file")" "$(cat "$file")"; then
            exit 0
        fi
        print_example
        exit 1
        ;;
    --range)
        range="${2:-}"
        if [[ -z "$range" ]]; then
            echo "error: --range needs a git revision range, e.g. origin/main..HEAD" >&2
            exit 64
        fi
        if ! commits="$(git rev-list --no-merges "$range" 2>/dev/null)"; then
            echo "error: '$range' is not a valid git revision range" >&2
            exit 64
        fi
        total=0
        failed=0
        for sha in $commits; do
            total=$((total + 1))
            if ! validate_message "$(git log -1 --format='%h %s' "$sha")" "$(git log -1 --format='%B' "$sha")"; then
                failed=$((failed + 1))
            fi
        done
        if (( failed > 0 )); then
            echo "" >&2
            echo "$failed of $total commit message(s) in '$range' violate Conventional Commits." >&2
            print_example
            exit 1
        fi
        echo "Conventional Commits OK: $total commit message(s) in '$range'"
        exit 0
        ;;
    --stdin)
        if validate_message "<stdin>" "$(cat)"; then
            exit 0
        fi
        print_example
        exit 1
        ;;
    --text)
        if validate_message "<argument>" "${2:-}"; then
            exit 0
        fi
        print_example
        exit 1
        ;;
    -h | --help | help)
        usage
        exit 0
        ;;
    '')
        usage >&2
        exit 64
        ;;
    *)
        echo "error: unknown option '$mode'" >&2
        usage >&2
        exit 64
        ;;
esac
